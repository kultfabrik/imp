const Font = {
  cache: {}, w: 6, h: 8,
  glyph(ch, color) {
    const key = ch + color;
    if (this.cache[key]) return this.cache[key];
    const src = FONT_SRC[ch] || FONT_SRC['?'];
    const c = document.createElement('canvas'); c.width = 5; c.height = 7;
    const g = c.getContext('2d'); g.fillStyle = color;
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (src[y][x] === '#') g.fillRect(x, y, 1, 1);
    this.cache[key] = c; return c;
  },
  width(txt) { return txt.length * this.w - 1; },
  draw(ctx, txt, x, y, color = '#fff', opts = {}) {
    txt = String(txt);
    let cx = x;
    if (opts.align === 'center') cx = Math.round(x - this.width(txt) / 2);
    else if (opts.align === 'right') cx = Math.round(x - this.width(txt));
    cx = Math.round(cx); y = Math.round(y);
    if (opts.shadow) { for (let i = 0; i < txt.length; i++) ctx.drawImage(this.glyph(txt[i], opts.shadow === true ? '#000' : opts.shadow), cx + i * this.w + 1, y + 1); }
    for (let i = 0; i < txt.length; i++) ctx.drawImage(this.glyph(txt[i], color), cx + i * this.w, y);
    return cx + txt.length * this.w;
  },
  // simple word wrap
  wrap(txt, maxChars) {
    const out = [];
    for (const para of String(txt).split('\n')) {
      let line = '';
      for (const word of para.split(' ')) {
        if ((line + ' ' + word).trim().length > maxChars) { out.push(line); line = word; }
        else line = (line ? line + ' ' : '') + word;
      }
      out.push(line);
    }
    return out;
  },
  drawWrapped(ctx, txt, x, y, maxChars, color, lineH = 9, opts = {}) {
    const lines = this.wrap(txt, maxChars);
    lines.forEach((l, i) => this.draw(ctx, l, x, y + i * lineH, color, opts));
    return lines.length;
  },
  // big text: scaled 2x
  drawBig(ctx, txt, x, y, color = '#fff', scale = 2, opts = {}) {
    txt = String(txt);
    const w = txt.length * this.w * scale - scale;
    let cx = x;
    if (opts.align === 'center') cx = Math.round(x - w / 2); else if (opts.align === 'right') cx = Math.round(x - w);
    ctx.imageSmoothingEnabled = false;
    if (opts.shadow) for (let i = 0; i < txt.length; i++) ctx.drawImage(this.glyph(txt[i], '#000'), cx + i * this.w * scale + scale, y + scale, 5 * scale, 7 * scale);
    for (let i = 0; i < txt.length; i++) ctx.drawImage(this.glyph(txt[i], color), cx + i * this.w * scale, y, 5 * scale, 7 * scale);
  }
};
