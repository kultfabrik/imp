const CH = {};
function chunk(name, str, extra) {
  const rows = str.split('\n').filter(r => r.trim().length || r.length > 3); const w = rows[0].length;
  rows.forEach((r, i) => { if (r.length !== w) throw new Error('chunk ' + name + ' row ' + i + ' width ' + r.length + ' != ' + w); });
  if (rows.length !== 15) throw new Error('chunk ' + name + ' height ' + rows.length);
  CH[name] = Object.assign({ rows, w }, extra || {});
}
