/* ---------- Assembler ---------- */
function assemble(seq, opts = {}) {
  const rows = Array.from({ length: 15 }, () => ''); const ents = []; const offline = []; const polls = []; const wartes = []; const tickets = []; const pipePlan = [];
  let x = 0, pollIdx = 0;
  for (const item of seq) {
    const name = typeof item === 'string' ? item : item.c; const c = CH[name]; if (!c) throw new Error('unknown chunk ' + name);
    const rep = (typeof item === 'object' && item.rep) || 1;
    for (let r = 0; r < rep; r++) {
      for (let y = 0; y < 15; y++) rows[y] += c.rows[y];
      if (c.offline) offline.push({ id: 'z' + offline.length, x0: x, x1: x + c.w - 1, range: c.range || 150 });
      if (c.poll) { const p = (typeof item === 'object' && item.poll) || (opts.polls && opts.polls[pollIdx]) || null; polls.push({ x, y: 0, def: p }); pollIdx++; }
      if (c.warte) wartes.push({ x });
      if (c.ticket) tickets.push({ x });
      if (c.pipes) pipePlan.push({ x0: x, x1: x + c.w, tags: c.pipes.slice() });
      const sfx = (e) => { const o = Object.assign({}, e, { x: e.x + x }); if (o.id) o.id = o.id + '@' + x; if (o.door) o.door = o.door + '@' + x; if (o.cells) o.cells = o.cells.map(cc => [cc[0] + x, cc[1]]); return o; };
      if (c.ents) for (const e of c.ents) ents.push(sfx(e));
      if (typeof item === 'object' && item.ents) for (const e of item.ents) ents.push(sfx(e));
      x += c.w;
    }
  }
  const map = rows.map(r => r.split(''));
  for (let y = 0; y < 15; y++) for (let xx = 0; xx < map[0].length; xx++) {
    const ch = map[y][xx];
    if ((ch === '{' || ch === '}') && (y === 0 || map[y - 1][xx] !== ch)) {
      let h = 1; while (y + h < 15 && map[y + h][xx] === ch) h++;
      const poll = polls.find(p => xx >= p.x && xx < p.x + 40); const id = (poll ? 'poll' + polls.indexOf(poll) : 'poll') + (ch === '{' ? 'A' : 'B');
      ents.push({ t: 'door', x: xx, y, id, h: h * TILE, hint: 'Der Chat entscheidet!' });
      for (let k = 0; k < h; k++) map[y + k][xx] = '.';
    }
  }
  for (const p of polls) { const i = polls.indexOf(p); ents.push({ t: 'poll', x: p.x + 1, y: 0, idx: i, A: (p.def && p.def.A) || 'Oben: Bits & Gefahr', B: (p.def && p.def.B) || 'Unten: sicher', doorA: 'poll' + i + 'A', doorB: 'poll' + i + 'B' }); }
  for (const w of wartes) {
    const cells = []; for (let y = 0; y < 15; y++) for (let xx = w.x; xx < w.x + 32; xx++) if (map[y][xx] === 'c') cells.push([xx, y]);
    cells.sort((a, b) => a[0] - b[0]); const nums = [47, 48, 49, 50].slice(0, cells.length);
    ents.push({ t: 'warte', x: 0, y: 0, cells, nums, door: 'warte' + wartes.indexOf(w) });
    ents.push({ t: 'door', x: w.x + 30, y: 3, id: 'warte' + wartes.indexOf(w), h: 160, hint: 'Wartenummern in Reihenfolge anstoßen: 47, 48, 49, 50' });
  }
  for (const t of tickets) { ents.push({ t: 'tdoor', x: t.x + 28, y: 3, id: 't' + tickets.indexOf(t), h: 160 }); }
  return { map: map.map(r => r.join('')), ents, offline, pipePlan };
}
/* vertical tower generator (w8) */
function genTower(seed, height, opts = {}) {
  const rng = makeRng(seed); const W = 20; const rows = []; for (let y = 0; y < height; y++) rows.push('%' + '.'.repeat(W - 2) + '%');
  const set = (x, y, ch) => { if (y >= 0 && y < height && x > 0 && x < W - 1) rows[y] = rows[y].slice(0, x) + ch + rows[y].slice(x + 1); };
  // floor
  for (let x = 0; x < W; x++) set(x, height - 1, '#'), set(x, height - 2, '#');
  let y = height - 5, side = 0, n = 0;
  const ents = [];
  // start platform row: wide, safe
  for (let x = 1; x < W - 1; x++) set(x, height - 3, '.');
  let prevX0 = 1, prevX1 = W - 2;
  while (y > 7) {
    let w = rng.int(5, 8), x0, x1;
    if (side === 0) { x0 = rng.int(1, 3); x1 = x0 + w - 1; if (prevX0 - x1 > 4) x1 = prevX0 - 4; }
    else { x1 = W - 2 - rng.int(0, 2); x0 = x1 - w + 1; if (x0 - prevX1 > 4) x0 = prevX1 + 4; }
    w = x1 - x0 + 1;
    for (let x = x0; x <= x1; x++) set(x, y, opts.solid ? '=' : '-');
    prevX0 = x0; prevX1 = x1;
    const r = rng();
    if (r < 0.18 && n > 2) set(x0 + Math.floor(w / 2), y - 1, opts.enemies ? rng.pick(opts.enemies) : 't');
    else if (r < 0.5) { set(x0 + 1, y - 2, 'b'); set(x0 + w - 2, y - 2, 'b'); }
    else if (r < 0.6 && opts.clickbait) { set(x0 + w + 1, y - 1, '8'); }
    else if (r < 0.7) { set(x0 + Math.floor(w / 2), y - 3, '?'); }
    if (rng() < 0.1 && n > 1) { for (let x = x0; x < x0 + w; x++) set(x, y - 1, '$'); }
    y -= 3; side = 1 - side; n++;
  }
  for (let x = 1; x < W - 1; x++) set(x, 5, '-'); for (let x = 7; x < 13; x++) set(x, 4, 'X'); set(9, 2, 'u'); set(10, 2, 'u'); set(9, 3, '|'); set(10, 3, '|'); set(3, 4, 'b'); set(15, 4, 'b'); set(5, 2, 'b'); set(13, 2, 'b');
  set(2, height - 4, 'P');
  return { map: rows, ents };
}
